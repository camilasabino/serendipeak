const SMALL_CUT_MAX_SIZE = 24;

/** Decorative: whoever places the mark supplies the accessible name. Rings take `currentColor`. */
export function BrandMark({ size }: { size: number }) {
	const cut = size <= SMALL_CUT_MAX_SIZE ? SMALL : REGULAR;

	return (
		<svg
			className={styles.mark}
			viewBox="0 0 64 64"
			width={size}
			height={size}
			aria-hidden="true"
			focusable="false"
		>
			<g className={styles.rings} strokeWidth={cut.stroke}>
				{cut.rings.map((d) => (
					<path key={d} d={d} />
				))}
			</g>
			<circle className={styles.summit} cx={cut.summit.cx} cy={cut.summit.cy} r={cut.summit.r} />
		</svg>
	);
}
